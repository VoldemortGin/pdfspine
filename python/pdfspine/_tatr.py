from copy import deepcopy
from dataclasses import dataclass, field, fields
from html import escape
import math
import os
import platform
from pathlib import Path
import sys
import threading
from typing import Any, Mapping

from . import _tatr_postprocess as _postprocess
from ._core import PdfUnsupportedError


DETECTION_MODEL = "microsoft/table-transformer-detection"
DETECTION_REVISION = "34669b5e93083671f6ccd7aca07d615a79772286"
STRUCTURE_MODEL = "microsoft/table-transformer-structure-recognition-v1.1-all"
STRUCTURE_REVISION = "7587a7ef111d9dcbf8ac695f1376ab7014340a0c"

_DETECTION_LABELS = {
    0: "table",
    1: "table rotated",
    2: "no object",
}
_STRUCTURE_LABELS = {
    0: "table",
    1: "table column",
    2: "table row",
    3: "table column header",
    4: "table projected row header",
    5: "table spanning cell",
    6: "no object",
}
_STRUCTURE_LABEL_IDS = {name: label for label, name in _STRUCTURE_LABELS.items()}


@dataclass(frozen=True)
class TatrOptions:
    """Validated options for the opt-in TATR backend."""

    dpi: int = 144
    device: str = "auto"
    detection_model: str = DETECTION_MODEL
    detection_revision: str | None = DETECTION_REVISION
    structure_model: str = STRUCTURE_MODEL
    structure_revision: str | None = STRUCTURE_REVISION
    detection_threshold: float = 0.5
    structure_threshold: float = 0.5
    crop_padding: int = 10
    local_files_only: bool = True
    ocr_if_no_text: bool = True
    native_line_guidance: bool = True
    adaptive_crop: bool = True
    ocr_engine: str = "paddle"
    ocr_language: str = "eng"

    def __post_init__(self) -> None:
        if type(self.dpi) is not int:
            raise TypeError("TATR dpi must be an int")
        if type(self.crop_padding) is not int:
            raise TypeError("TATR crop_padding must be an int")
        for name in ("detection_threshold", "structure_threshold"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise TypeError(f"TATR {name} must be a real number")
            object.__setattr__(self, name, float(value))
        for name in (
            "device",
            "detection_model",
            "structure_model",
            "ocr_engine",
            "ocr_language",
        ):
            if not isinstance(getattr(self, name), str):
                raise TypeError(f"TATR {name} must be a string")
        object.__setattr__(self, "device", self.device.casefold().strip())
        for name in ("detection_revision", "structure_revision"):
            value = getattr(self, name)
            if value is not None and not isinstance(value, str):
                raise TypeError(f"TATR {name} must be a string or None")
        for name in (
            "local_files_only",
            "ocr_if_no_text",
            "native_line_guidance",
            "adaptive_crop",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"TATR {name} must be a bool")
        self._validate()

    @classmethod
    def from_mapping(cls, value: Mapping[str, object] | None) -> "TatrOptions":
        if value is None:
            result = cls()
        elif not isinstance(value, Mapping):
            raise TypeError("vision_options must be a mapping or None")
        else:
            known = {field.name for field in fields(cls)}
            unknown = sorted((key for key in value if key not in known), key=str)
            if unknown:
                raise TypeError(
                    "unknown TATR option(s): " + ", ".join(str(k) for k in unknown)
                )
            result = cls(**dict(value))  # type: ignore[arg-type]
        return result

    def _validate(self) -> None:
        if not 36 <= self.dpi <= 600:
            raise ValueError("TATR dpi must be between 36 and 600")
        if not math.isfinite(self.detection_threshold):
            raise ValueError("TATR detection_threshold must be finite")
        if not 0.0 <= self.detection_threshold <= 1.0:
            raise ValueError("TATR detection_threshold must be in [0, 1]")
        if not math.isfinite(self.structure_threshold):
            raise ValueError("TATR structure_threshold must be finite")
        if not 0.0 <= self.structure_threshold <= 1.0:
            raise ValueError("TATR structure_threshold must be in [0, 1]")
        if not 0 <= self.crop_padding <= 20:
            raise ValueError("TATR crop_padding must be between 0 and 20 pixels")
        if self.device not in {"auto", "cpu", "cuda", "mps"}:
            cuda_prefix, separator, cuda_index = self.device.partition(":")
            if cuda_prefix != "cuda" or separator != ":" or not cuda_index.isdecimal():
                raise ValueError(
                    "TATR device must be 'auto', 'cpu', 'cuda', 'cuda:N', or 'mps'"
                )
        if not self.detection_model.strip() or not self.structure_model.strip():
            raise ValueError("TATR model identifiers must not be empty")
        if not self.ocr_engine.strip() or not self.ocr_language.strip():
            raise ValueError("TATR OCR engine and language must not be empty")


@dataclass
class _RenderedPage:
    image: Any
    tokens: list[dict[str, Any]]
    page_bbox: tuple[float, float, float, float]
    scale_x: float
    scale_y: float
    text_source: str
    rotation: int = 0
    unrotated_size: tuple[float, float] | None = None


@dataclass
class _TableCrop:
    image: Any
    tokens: list[dict[str, Any]]

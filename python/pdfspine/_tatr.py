"""Optional Microsoft Table Transformer (TATR) table backend.

The two neural networks only predict table regions and structure.  Cell text is
always filled from pdfspine's native word coordinates (or its built-in OCR when
the page has no text layer), so numeric strings are not regenerated by a model.

Torch, Transformers and Pillow are imported lazily.  Importing :mod:`pdfspine`
therefore has no ML dependency and never loads or downloads a checkpoint.
"""


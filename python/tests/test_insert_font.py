def aliased_synthetic_font():
    """Give A/B one glyph and space/NBSP another in the generated format-4 cmap."""
    import struct

    data = bytearray(SYNTHETIC_TTF)
    tables = struct.unpack_from(">H", data, 4)[0]
    cmap = next(
        struct.unpack_from(">I", data, 12 + 16 * i + 8)[0]
        for i in range(tables)
        if data[12 + 16 * i : 16 + 16 * i] == b"cmap"
    )
    sub = cmap + struct.unpack_from(">I", data, cmap + 8)[0]
    segments = struct.unpack_from(">H", data, sub + 6)[0] // 2
    delta = sub + 16 + 4 * segments
    struct.pack_into(">H", data, delta + 2 * 2, (2 - ord("B")) & 0xFFFF)
    # The fourth sorted segment was é: replace it with NBSP, mapping to space GID 1.
    struct.pack_into(">H", data, sub + 14 + 3 * 2, 0xA0)
    struct.pack_into(">H", data, sub + 16 + 2 * segments + 3 * 2, 0xA0)
    struct.pack_into(">H", data, delta + 3 * 2, (1 - 0xA0) & 0xFFFF)
    return bytes(data)


def test_two_unicode_pairs_sharing_gids_keep_distinct_cids_after_reopen():
    doc = pdfspine.open()
    page = doc.new_page()
    page.insert_font(fontname="Aliases", fontbuffer=aliased_synthetic_font())
    page.insert_text((40, 70), "A B\u00a0A", fontname="Aliases")
    reopened = pdfspine.open(stream=doc.tobytes(), filetype="pdf")
    reopened[0].insert_text((40, 100), "BA\u00a0B A", fontname="Aliases")
    assert "A B\u00a0A" in reopened[0].get_text()
    assert "BA\u00a0B A" in reopened[0].get_text()


def synthetic_with_cmap_groups(format_number, groups):
    """Replace the generated cmap with a bounded format-12/13 test program."""
    import struct

    data = bytearray(SYNTHETIC_TTF)
    tables = struct.unpack_from(">H", data, 4)[0]
    record = next(
        12 + 16 * i for i in range(tables) if data[12 + 16 * i : 16 + 16 * i] == b"cmap"
    )
    offset, capacity = struct.unpack_from(">II", data, record + 8)
    sub = struct.pack(">HHIII", format_number, 0, 16 + len(groups) * 12, 0, len(groups))
    sub += b"".join(struct.pack(">III", *group) for group in groups)
    cmap = struct.pack(">HHHHI", 0, 1, 3, 10, 12) + sub
    assert len(cmap) <= capacity
    data[offset : offset + len(cmap)] = cmap
    struct.pack_into(">I", data, record + 12, len(cmap))
    return bytes(data)


def test_astral_cmap_character_survives_registered_reopen():
    program = synthetic_with_cmap_groups(12, [(0x41, 0x41, 2), (0x1F600, 0x1F600, 3)])
    doc = pdfspine.open()
    page = doc.new_page()
    page.insert_font(fontname="Astral", fontbuffer=program)
    page.insert_text((40, 70), "A😀", fontname="Astral")
    reopened = pdfspine.open(stream=doc.tobytes(), filetype="pdf")
    reopened[0].insert_text((40, 100), "😀A", fontname="Astral")
    assert reopened[0].get_text().splitlines() == ["A😀", "😀A"]



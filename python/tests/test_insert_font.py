def test_core14_registration_reuses_xref_without_writing_contents():
    doc = pdfspine.open()
    page = doc.new_page()
    before = page.get_contents()
    xref = page.insert_font(fontname="helv")
    assert isinstance(xref, int) and xref > 0
    assert page.get_contents() == before
    assert page.insert_font(fontname="/helv", fontbuffer=b"invalid") == xref
    page.insert_text((40, 70), "Registered text", fontname="helv")
    reopened = pdfspine.open(stream=doc.tobytes(), filetype="pdf")
    assert "Registered text" in reopened[0].get_text()



@pytest.mark.parametrize("source", ["buffer", "file"])
def test_registered_truetype_reused_by_text_and_survives_reopen(tmp_path, source):
    doc = pdfspine.open()
    page = doc.new_page()
    kwargs = {"fontbuffer": SYNTHETIC_TTF}
    if source == "file":
        path = tmp_path / "generated.ttf"
        path.write_bytes(SYNTHETIC_TTF)
        kwargs = {"fontfile": path}
    before_contents = page.get_contents()
    xref = page.insert_font(fontname="Custom", **kwargs)
    assert page.get_contents() == before_contents
    page.insert_text((40, 70), "AB ΩЖé", fontname="Custom", fontsize=20)
    assert page.insert_font(fontname="Custom", fontbuffer=b"bad") == xref
    reopened = pdfspine.open(stream=doc.tobytes(), filetype="pdf")
    assert "AB ΩЖé" in reopened[0].get_text()
    assert len(reopened[0].get_fonts()) == 1
    assert reopened[0].get_fonts()[0][0] == xref



def test_shared_glyph_unicode_aliases_survive_reopen_and_append():
    from pathlib import Path

    font = (
        Path(__file__).resolve().parents[2]
        / "crates/pdf-fonts/fonts/liberation/LiberationSans-Regular.ttf"
    )
    doc = pdfspine.open()
    page = doc.new_page()
    xref = page.insert_font(fontname="Registered", fontfile=font)
    page.insert_text((40, 70), "A B\u00a0A", fontname="Registered")
    reopened = pdfspine.open(stream=doc.tobytes(), filetype="pdf")
    reopened[0].insert_text((40, 100), "B\u00a0A B", fontname="Registered")
    final = pdfspine.open(stream=reopened.tobytes(), filetype="pdf")
    assert "A B\u00a0A" in final[0].get_text()
    assert "B\u00a0A B" in final[0].get_text()
    assert final[0].get_fonts()[0][0] == xref


def test_registered_textbox_uses_composite_widths_and_encoding():
    doc = pdfspine.open()
    page = doc.new_page()
    page.insert_font(fontname="Custom", fontbuffer=SYNTHETIC_TTF)
    # Two 700-unit glyphs at 20pt occupy 28pt; a space and a second word
    # require 70pt. This width therefore places the words on separate lines.

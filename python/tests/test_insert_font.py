def test_inherited_fonts_preserved_without_mutating_shared_parent():
    doc = pdfspine.open()
    page = doc.new_page()
    doc.new_page()
    page = doc[0]
    font = doc.get_new_xref()
    doc.update_object(
        font,
        "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
    )
    parent = int(doc.xref_get_key(page.xref, "Parent").split()[0])
    doc.xref_set_key(parent, "Resources", f"<< /Font << /Existing {font} 0 R >> >>")
    doc.xref_set_key(page.xref, "Resources", "null")
    before_parent = doc.xref_object(parent)
    assert page.insert_font(fontname="Existing", fontbuffer=b"bad") == font
    page.insert_font(fontname="helv")
    assert doc.xref_object(parent) == before_parent
    assert {entry[4] for entry in page.get_fonts()} == {"Existing", "helv"}
    page.insert_text((40, 70), "AB", fontname="Existing", fontsize=20)
    assert page.get_text().strip() == "AB"


